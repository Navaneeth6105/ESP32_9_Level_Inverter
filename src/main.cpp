void start_50kHz_timer() {
    // Timer 0, prescaler 80 (80 MHz / 80 = 1 MHz = 1µs per tick), count up
    timer_50kHz = timerBegin(0, 80, true);
    // 2. Attach your interrupt function
    timerAttachInterrupt(timer_50kHz, &onTimerISR, true);
    // 3. Set alarm to fire every 20 microseconds (1,000,000 µs / 50,000 Hz = 20 µs)
    //    true = auto-reload (periodic)
    timerAlarmWrite(timer_50kHz, 20, true);
    // 4. Start the timer
    timerAlarmEnable(timer_50kHz);
}

void make_tri_lut(){
  for(int i = 1 ; i < CARRIER_NO_SIZE ; i++){
    for(int j = 0 ; j < TRIANGLE_LUT_SIZE ; j++)
      tri_lut[i][j] = tri_lut[i-1][j] + 200000000 ;
  }
}



void stop_50kHz_timer() {
    if (timer_50kHz != NULL) {
        timerAlarmDisable(timer_50kHz);
        timerDetachInterrupt(timer_50kHz);
        timerEnd(timer_50kHz);
        timer_50kHz = NULL;
    }
}

